import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { publicMemberAccessFixture } from '../verification/public-member-access.mjs';
import { installMemberCordis } from '../carrier/cordis.mjs';

const modules = process.env.DSH_LAN_CONTRACT_MODULES;
test('native Cordis client manifests, query deliveries and replies stay with their member account', { skip: !modules, timeout: 15000 }, async t => {
  const directory = await mkdtemp(join(tmpdir(), 'dsh-member-cordis-'));
  const f = await publicMemberAccessFixture({ modules, directory, memberPolicy: false });
  t.after(async () => { await f.close(); await rm(directory, { recursive: true }); });
  const load = name => import(pathToFileURL(join(modules, '@deepseek-ai', name, 'lib/index.js')).href);
  const fibers = [];
  t.after(async () => { for (const fiber of fibers.reverse()) await fiber.dispose(); });
  for (const name of ['dsh-system-prompt', 'dsh-tools', 'dsh-cordis-host-runner']) { const fiber = f.host.plugin((await load(name)).default, {}); fibers.push(fiber); await fiber.await(); }
  const wire = await import(pathToFileURL(join(modules, '@deepseek-ai/dsh-cordis-host-runner/lib/typert.host.js')).href);
  const wireFiber = f.host.plugin(ctx => ctx.typert.register(wire.TYPERT)); fibers.push(wireFiber); await wireFiber.await();
  const ownerOf = id => ({ 'alice-session': 'alice', 'bob-session': 'bob' })[id];
  const removePolicy = f.host.remoteAccess.registerPolicy('lan-member', { bindings(principal) { return [{ resource: { kind: 'global' }, role: { name: 'cordis-read', actions: ['dynamicCordisRunner/syncInspectManifest', 'dynamicCordisRunner/inventory'] } }]; } });
  t.after(removePolicy);
  const runner = f.host.get('dynamicCordisRunner'), gateway = f.host.get('typertGateway'), registry = f.host.get('cordisInspect');
  const unregister = gateway.registerRemoteEvents(async function*(signal) { if (!signal.aborted) await new Promise(resolve => signal.addEventListener('abort', resolve, { once: true })); }, { home: '/synthetic-owner-home' });
  t.after(unregister);
  let revoked = false;
  const restore = installMemberCordis(runner, gateway, { ownership: { ownerOf }, models: { userOf: ownerOf, requestUser: () => ownerOf(f.host.get('agents').currentInitiator()?.id) }, capabilities: { policy(userId) { if (userId === 'alice' && revoked) throw Error('revoked'); return {}; } } });
  t.after(restore);
  const open = async name => { const control = new AbortController(); const stream = (await gateway.wireStream.open('$events', { args: {} }, undefined, f.peer(name), control.signal))[Symbol.asyncIterator](); await stream.next(); return { stream, control }; };
  const a = await open('alice'), b = await open('bob');
  t.after(async () => { a.control.abort(); b.control.abort(); await a.stream.return(); await b.stream.return(); });
  const manifest = id => ({ id, description: 'Synthetic member inspect', methods: [{ name: 'read', description: 'Read fixture', inputSchema: { type: 'object' }, outputSchema: { type: 'string' } }] });
  assert.equal((await f.http('alice', 'dynamicCordisRunner/syncInspectManifest', { providers: [manifest('a')] })).result.ok, true);
  assert.equal((await f.http('bob', 'dynamicCordisRunner/syncInspectManifest', { providers: [manifest('b')] })).result.ok, true);
  assert.deepEqual(registry.list(), [], 'member sync leaves owner mirror alone');
  const actor = id => ({ id });
  const list = id => f.host.get('agents').withInitiator(actor(id), () => registry.list().map(x => x.id));
  assert.deepEqual(list('alice-session'), ['a']); assert.deepEqual(list('bob-session'), ['b']);
  const emit = f.host.on('cordis/inspect-query', request => gateway.broadcastRemoteEvent({ event: 'cordis/inspect-query', args: [request] })); t.after(emit);
  const pending = registry.query('client', 'a', 'read', {}, actor('alice-session'), AbortSignal.timeout(3000));
  const frame = (await a.stream.next()).value;
  assert.equal(frame.args[0].agentId, 'alice-session');
  const bClient = [...gateway.remoteEventClients.values()].find(x => x.principal.userId === 'bob');
  assert.equal(bClient.queue.frames.size, 0);
  const requestId = frame.args[0].requestId;
  const scopedRunner = name => f.host.extend({ invocation: { peer: f.peer(name) } }).get('dynamicCordisRunner');
  assert.equal(scopedRunner('bob').resolveInspectQuery(actor('alice-session'), requestId, { ok: true, data: 'forged' }).accepted, false);
  assert.equal(scopedRunner('alice').resolveInspectQuery(actor('alice-session'), requestId, { ok: true, data: 'A_ONLY' }).accepted, true);
  assert.equal(await pending, 'A_ONLY');
  assert.equal(scopedRunner('alice').resolveInspectQuery(actor('alice-session'), requestId, { ok: true, data: 'late' }).accepted, false);
  revoked = true;
  await assert.rejects(f.http('alice', 'dynamicCordisRunner/syncInspectManifest', { providers: [] }).then(x => { if (!x.result.ok) throw Error(x.result.error.message); }), /revoked/);
});
