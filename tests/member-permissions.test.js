import { updateAccount } from './helpers/account-update.js';
import test from 'node:test';
import assert from 'node:assert/strict';
import { accountAccess } from '../core/validation.js';
import { LanService, MemoryStore } from '../core/service.js';
import { MemberOwnership } from '../carrier/access.mjs';
import { MemberModels } from '../carrier/models.mjs';
import { MemberCapabilities } from '../carrier/capabilities.mjs';
import { installMemberPermissions, installMemberCommands } from '../carrier/permissions.mjs';
import { memberExecutionFixture } from '../verification/member-execution-fixture.mjs';
const modules = process.env.DSH_LAN_CONTRACT_MODULES;

test('native permission presets and commands respect account grants while execution retains the selected native full-access policy', { skip: !modules || process.platform !== 'linux' }, async t => {
  const f = await memberExecutionFixture({ modules, parent: process.cwd(), ptc: true }); t.after(() => f.close());
  f.provide('sessions', { list: () => [f.agent.session] });
  f.provide('approval', { config: { policy: 'ask' }, setPolicy(agent, policy) { agent.session.append('approval/policy', { policy }); } });
  await f.mountService('dsh-commands');
  await f.mountService('dsh-permission-presets', { defaultPreset: 'workspace-write', presets: {
    'read-only': { sandbox: 'read-only', approval: 'ask' }, 'workspace-write': { sandbox: 'workspace-write', approval: 'ask' }, 'danger-full-access': { sandbox: 'danger-full-access', approval: 'never' },
  } });
  const store = new MemoryStore(), cap = {}, core = new LanService({ store, hostCapability: cap }); await core.start(); await core.setModelCatalog([]); t.after(() => core.close());
  const password = 'synthetic-permission-password';
  const login = await core.execute({ action: 'bootstrap', username: 'admin', displayName: 'Admin', password }, { ownerBootstrap: true, audience: 'owner' });
  const admin = { token: login.token, csrf: login.csrf, audience: 'owner' };
  const userId = (await core.execute({ action: 'admin.createUser', username: 'alice', displayName: 'Alice', password }, admin)).user.id;
  const ownership = await new MemberOwnership({ store: new MemoryStore() }).start(); await ownership.record({ userId, sessionId: f.agent.id, projectId: 'workspace', cwd: f.cwd });
  const ctx = { agents: { get: id => id === f.agent.id ? f.agent : undefined, currentInitiator: () => undefined } };
  const models = new MemberModels({ core, hostCapability: cap, ownership, ctx }), capabilities = new MemberCapabilities({ core, hostCapability: cap, ownership, ctx });
  const permissions = f.services.get('permissionPresets'), commands = f.services.get('commands');
  const restorePermissions = installMemberPermissions(permissions, { models, capabilities, ownership }); t.after(restorePermissions);
  const restoreCommands = installMemberCommands(commands, { models, capabilities }); t.after(restoreCommands);
  const update = access => updateAccount(core, { action: 'admin.updateUser', userId, access }, admin);
  await update({ permissionPresets: ['read-only'] });
  permissions.pinInitialPermission(f.agent.session);
  assert.equal(permissions.current(f.agent.session), 'read-only');
  assert.deepEqual(capabilities.permissionPresetCatalog(userId, permissions.catalog()).options.map(x => x.value), ['read-only']);
  assert.equal((await f.run('write', { file_path: 'readonly.txt', content: 'bad' })).isError, true);
  await assert.rejects(commands.execute(f.agent, '/permission danger-full-access', [], AbortSignal.timeout(1000)), { code: 'MEMBER_CAPABILITY_DENIED' });
  assert.equal(permissions.current(f.agent.session), 'read-only');
  await update({ permissionPresets: ['read-only', 'danger-full-access'] });
  const escalation = { agent: f.agent, name: 'write', arguments: { sandbox_permissions: 'danger-full-access' } };
  assert.equal(capabilities.toolDenial(escalation, 'read-only'), undefined, 'authorized per-call escalation reaches native approval');
  assert.match(capabilities.toolDenial({ ...escalation, arguments: { sandbox_permissions: 'workspace-write' } }, 'read-only'), /cannot leave/);
  const full = await commands.execute(f.agent, '/permission danger-full-access', [], AbortSignal.timeout(1000));
  assert.equal(full.result.kind, 'success', JSON.stringify(full));
  assert.equal(permissions.current(f.agent.session), 'danger-full-access');
  assert.equal(f.services.sandboxPolicy.resolve({ session: f.agent.session }).mode, 'danger-full-access');
  assert.equal((await f.run('write', { file_path: 'allowed.txt', content: 'yes' })).isError, false);
  assert.equal((await f.run('bash', { description: 'Native full access', command: `test -e '${f.canary}'` })).value?.exitCode, 0);
  await update({ permissionPresets: ['read-only'], tasks: false });
  assert.match(capabilities.toolDenial(escalation, 'read-only'), /cannot leave/);
  permissions.pinInitialPermission(f.agent.session);
  assert.equal(permissions.current(f.agent.session), 'read-only');
  assert.throws(() => permissions.set(f.agent.session, 'danger-full-access'), { code: 'MEMBER_CAPABILITY_DENIED' });
  assert.equal(permissions.defaultPreset, 'workspace-write');
  assert.equal(permissions.catalog().options.length, 3, 'host catalog unchanged');
  let called = false;
  commands.register({ definitionId: 'synthetic-goal', name: 'goal', description: 'Goal contract', handler() { called = true; return { kind: 'success' }; } });
  assert.equal(commands.list(f.agent).some(x => x.name === 'goal'), false);
  await assert.rejects(commands.execute(f.agent, '/goal', [], AbortSignal.timeout(1000)), { code: 'MEMBER_CAPABILITY_DENIED' }); assert.equal(called, false);
  await update({ tools: ['read'] });
  const restarted = new LanService({ store, hostCapability: cap }); await restarted.start(); t.after(() => restarted.close());
  assert.deepEqual(restarted.memberAccess(userId, cap).permissionPresets, ['read-only']);
  assert.equal(accountAccess().permissionPresets, null);
});
